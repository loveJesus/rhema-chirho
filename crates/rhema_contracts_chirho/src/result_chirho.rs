//! Result schema — stable DTOs for query results, independent of
//! internal storage. Used by GUI, REST, CLI, and AI surfaces.

use serde::{Deserialize, Serialize};

use crate::ids_chirho::TokenPositionChirho;
use crate::keys_chirho::VerseRefChirho;

/// A single search result hit.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SearchHitChirho {
    /// The verse this hit is in.
    pub verse_ref_chirho: VerseRefChirho,
    /// The rendered text of the verse.
    pub text_chirho: String,
    /// Highlighted text with matched terms marked.
    pub highlighted_text_chirho: Option<String>,
    /// Relevance score (0.0 - 1.0).
    pub score_chirho: f32,
    /// Which tokens matched.
    pub matched_positions_chirho: Vec<TokenPositionChirho>,
    /// Explain payload (if requested).
    pub explain_chirho: Option<ExplainPayloadChirho>,
    /// Semantic similarity score from vector search (if applicable).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub semantic_score_chirho: Option<f32>,
    /// Final hybrid score after merging keyword + semantic (if applicable).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub hybrid_score_chirho: Option<f32>,
    /// Human-readable explanation of why this hit was semantically relevant.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub semantic_explain_chirho: Option<String>,
}

/// Explanation of why a result matched.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ExplainPayloadChirho {
    /// Which fields contributed to the match.
    pub matched_fields_chirho: Vec<String>,
    /// Score contribution per operator.
    pub score_breakdown_chirho: Vec<ScoreComponentChirho>,
    /// Positional match window data.
    pub position_windows_chirho: Vec<PositionWindowChirho>,
}

/// A single score contribution from an operator.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ScoreComponentChirho {
    pub operator_chirho: String,
    pub weight_chirho: f32,
    pub contribution_chirho: f32,
}

/// Positional window for proximity matches.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PositionWindowChirho {
    pub start_position_chirho: TokenPositionChirho,
    pub end_position_chirho: TokenPositionChirho,
    pub span_chirho: u32,
}

/// Result of LLM-based query expansion.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct QueryExpansionResultChirho {
    /// The original user query.
    pub original_query_chirho: String,
    /// Expanded terms generated by the LLM.
    pub expanded_terms_chirho: Vec<String>,
    /// Expanded Strong's numbers.
    pub expanded_strongs_chirho: Vec<String>,
    /// Strategy used for expansion.
    pub strategy_chirho: String,
}

/// Complete query result set.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct QueryResultChirho {
    /// The hits.
    pub hits_chirho: Vec<SearchHitChirho>,
    /// Total matching hits (may be > hits.len() if capped by max_results).
    pub total_count_chirho: u64,
    /// Execution time in microseconds.
    pub execution_time_us_chirho: u64,
    /// Which backend executed this query.
    pub backend_chirho: String,
    /// The execution plan used (if explain requested).
    pub plan_chirho: Option<String>,
    /// Whether AI was used in this query execution.
    #[serde(default)]
    pub used_ai_chirho: bool,
    /// Query expansion details (if LLM expansion was used).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub query_expansion_chirho: Option<QueryExpansionResultChirho>,
}

#[cfg(test)]
mod tests_chirho {
    use super::*;

    fn make_hit_chirho(book_chirho: &str, ch_chirho: u16, v_chirho: u16) -> SearchHitChirho {
        SearchHitChirho {
            verse_ref_chirho: VerseRefChirho::new_chirho(book_chirho, ch_chirho, v_chirho).unwrap(),
            text_chirho: format!("{} {}:{} text", book_chirho, ch_chirho, v_chirho),
            highlighted_text_chirho: None,
            score_chirho: 1.0,
            matched_positions_chirho: Vec::new(),
            explain_chirho: None,
            semantic_score_chirho: None,
            hybrid_score_chirho: None,
            semantic_explain_chirho: None,
        }
    }

    #[test]
    fn test_search_hit_serde_chirho() {
        let hit_chirho = make_hit_chirho("John", 3, 16);
        let json_chirho = serde_json::to_string(&hit_chirho).unwrap();
        let parsed_chirho: SearchHitChirho = serde_json::from_str(&json_chirho).unwrap();
        assert_eq!(parsed_chirho.verse_ref_chirho.book_chirho, "John");
        assert_eq!(parsed_chirho.score_chirho, 1.0);
    }

    #[test]
    fn test_search_hit_with_highlight_chirho() {
        let mut hit_chirho = make_hit_chirho("Rom", 8, 28);
        hit_chirho.highlighted_text_chirho =
            Some("all things work together for <b>good</b>".to_string());
        assert!(hit_chirho.highlighted_text_chirho.is_some());
    }

    #[test]
    fn test_search_hit_with_positions_chirho() {
        let mut hit_chirho = make_hit_chirho("Gen", 1, 1);
        hit_chirho.matched_positions_chirho =
            vec![TokenPositionChirho(0), TokenPositionChirho(5)];
        assert_eq!(hit_chirho.matched_positions_chirho.len(), 2);
    }

    #[test]
    fn test_query_result_serde_chirho() {
        let result_chirho = QueryResultChirho {
            hits_chirho: vec![make_hit_chirho("John", 3, 16)],
            total_count_chirho: 1,
            execution_time_us_chirho: 1234,
            backend_chirho: "tantivy".to_string(),
            plan_chirho: None,
            used_ai_chirho: false,
            query_expansion_chirho: None,
        };
        let json_chirho = serde_json::to_string(&result_chirho).unwrap();
        let parsed_chirho: QueryResultChirho = serde_json::from_str(&json_chirho).unwrap();
        assert_eq!(parsed_chirho.total_count_chirho, 1);
        assert_eq!(parsed_chirho.backend_chirho, "tantivy");
    }

    #[test]
    fn test_query_result_with_plan_chirho() {
        let result_chirho = QueryResultChirho {
            hits_chirho: Vec::new(),
            total_count_chirho: 0,
            execution_time_us_chirho: 500,
            backend_chirho: "regex".to_string(),
            plan_chirho: Some("FullTextSearch('love')".to_string()),
            used_ai_chirho: false,
            query_expansion_chirho: None,
        };
        assert!(result_chirho.plan_chirho.is_some());
    }

    #[test]
    fn test_explain_payload_serde_chirho() {
        let payload_chirho = ExplainPayloadChirho {
            matched_fields_chirho: vec!["text".to_string()],
            score_breakdown_chirho: vec![ScoreComponentChirho {
                operator_chirho: "term".to_string(),
                weight_chirho: 1.0,
                contribution_chirho: 0.8,
            }],
            position_windows_chirho: vec![PositionWindowChirho {
                start_position_chirho: TokenPositionChirho(10),
                end_position_chirho: TokenPositionChirho(15),
                span_chirho: 5,
            }],
        };
        let json_chirho = serde_json::to_string(&payload_chirho).unwrap();
        let parsed_chirho: ExplainPayloadChirho = serde_json::from_str(&json_chirho).unwrap();
        assert_eq!(parsed_chirho.matched_fields_chirho.len(), 1);
        assert_eq!(parsed_chirho.score_breakdown_chirho[0].contribution_chirho, 0.8);
    }
}
